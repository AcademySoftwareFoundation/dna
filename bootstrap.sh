    echo -e "${BOLD}${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
    echo -e "${BOLD}${BLUE}  DNA — Settings${NC}"
    echo -e "${BOLD}${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
    echo ""
    info "Existing config found. Choose one setting to change."
    echo ""

    while true; do
        local llm_label route_label pt_label flags_label settings_choice
        llm_label="$(current_llm_label)"
        route_label="$(current_transcription_label)"
        pt_label="$(current_prodtrack_label)"
        flags_label="$(current_feature_flags_label)"

        echo -e "${BOLD}Settings${NC}"
        echo "  1) LLM provider            (${llm_label})"
        echo "  2) Transcription           (${route_label})"
        echo "  3) Production tracking     (${pt_label})"
        echo "  4) Feature flags           (${flags_label})"
        echo "  5) Done"
        echo ""
        if ! read -r -p "  Choice: " settings_choice; then
            echo ""
            ok "No further changes."
            restart_backend_if_running
            return 0
        fi
        echo ""

        case "$settings_choice" in
            1)
                configure_llm
                remind_restart
                ;;
            2)
                choose_transcription_route
                apply_transcription_route
                maybe_bootstrap_vexa_key
                remind_restart
                ;;
            3)
                configure_prodtrack
                remind_restart
                ;;
            4)
                configure_feature_flags
                remind_restart
                ;;
            5|[dD]one|[qQ]|[qQ]uit)
                ok "No further changes."
                restart_backend_if_running
                return 0
                ;;
            *)
                warn "Enter 1-5."
                ;;
        esac
        echo ""
    done
}

# ── main ───────────────────────────────────────────────────────────────────────

main() {
    local start_only=false
    for arg in "$@"; do
        case "$arg" in
            --start) start_only=true ;;
            *) die "Unknown argument: $arg. Usage: ./bootstrap.sh [--start]" ;;
        esac
    done

    echo ""
    if [[ "$start_only" == "true" ]]; then
        echo -e "${BOLD}${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
        echo -e "${BOLD}${BLUE}  DNA — Start${NC}"
        echo -e "${BOLD}${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
        echo ""
        check_prerequisites
        echo ""
        TRANSCRIPTION_ROUTE="$(detect_transcription_route)"
        start_full_stack "$TRANSCRIPTION_ROUTE"
        echo ""
        wait_for_dna "$TRANSCRIPTION_ROUTE"
        print_summary "DNA is running!" "$TRANSCRIPTION_ROUTE"
    elif env_is_initialized; then
        change_settings
    else
        echo -e "${BOLD}${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
        echo -e "${BOLD}${BLUE}  DNA — Bootstrap${NC}"
        echo -e "${BOLD}${BLUE}━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━${NC}"
        echo ""
        check_prerequisites
        echo ""
        choose_transcription_route
        copy_config_files
        echo ""
        configure_llm
        apply_transcription_route
        configure_prodtrack
        configure_feature_flags
        install_frontend
        echo ""
        if [[ "$TRANSCRIPTION_ROUTE" == "extension" ]]; then
            info "Skipping Vexa bootstrap (browser-extension transcription route)"
        elif [[ "$VEXA_HOSTED" != "true" ]]; then
            bootstrap_vexa
            echo ""
        fi
        start_full_stack "$TRANSCRIPTION_ROUTE"
        echo ""
        wait_for_dna "$TRANSCRIPTION_ROUTE"
        print_summary "Bootstrap complete!" "$TRANSCRIPTION_ROUTE"
    fi
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then
    main "$@"
fi
