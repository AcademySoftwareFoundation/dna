# ── helpers ────────────────────────────────────────────────────────────────────

get_compose_cmd() {
    if command -v docker-compose &>/dev/null; then
        echo "docker-compose"
    else
        echo "docker compose"
    fi
}

# Back up $dst if it already exists, then copy $src → $dst.
safe_copy() {
    local src="$1" dst="$2"
    if [[ -f "$dst" ]]; then
        rm -f "${dst}".bak.*
        local bak="${dst}.bak.$(date +%Y%m%d%H%M%S)"
        warn "$(basename "$dst") already exists — backed up to $(basename "$bak")"
        cp "$dst" "$bak"
    fi
    cp "$src" "$dst"
    ok "$(basename "$src") → $(basename "$dst")"
}

# Docker Compose interpolates $VAR and ${VAR} in environment values. A literal
# dollar sign in a secret has to be written as $$.
escape_compose_value() {
    local value="$1"
    printf '%s' "${value//\$/\$\$}"
}

# Replace `- KEY=...` environment entries. Comments that mention KEY= are left
# alone so a value cannot truncate the rest of the line.
set_env_var() {
    local key="$1" value="$2" file="$3"
    local escaped
    escaped="$(escape_compose_value "$value")"
    python3 - "$file" "$key" "$escaped" <<'PYEOF'
import sys

path, key, value = sys.argv[1], sys.argv[2], sys.argv[3]
with open(path) as f:
    lines = f.readlines()

prefix = f"{key}="
changed = False
for i, line in enumerate(lines):
    stripped = line.lstrip()
    if not stripped.startswith("- "):
        continue
    body = stripped[2:]
    if not body.startswith(prefix):
        continue
    indent = line[: len(line) - len(stripped)]
    lines[i] = f"{indent}- {prefix}{value}\n"
    changed = True

if changed:
    with open(path, "w") as f:
        f.writelines(lines)
PYEOF
}

# Set KEY=VALUE in a compose environment block, appending if the key is absent.
ensure_env_var() {
    local key="$1" value="$2" file="$3"
    if grep -qE "^[[:space:]]*-[[:space:]]*${key}=" "$file" 2>/dev/null; then
        set_env_var "$key" "$value" "$file"
        return
    fi
    local escaped
    escaped="$(escape_compose_value "$value")"
    python3 - "$file" "$key" "$escaped" <<'PYEOF'
import sys

path, key, value = sys.argv[1], sys.argv[2], sys.argv[3]
with open(path) as f:
    lines = f.readlines()

last_env_idx = -1
for i, line in enumerate(lines):
    stripped = line.lstrip()
    if stripped.startswith("- ") and "=" in stripped:
        last_env_idx = i

if last_env_idx < 0:
    sys.exit(1)

indent = lines[last_env_idx][: len(lines[last_env_idx]) - len(lines[last_env_idx].lstrip())]
lines.insert(last_env_idx + 1, f"{indent}- {key}={value}\n")
with open(path, "w") as f:
    f.writelines(lines)
PYEOF
}

# Set a frontend VITE_* flag, uncommenting the line if it ships commented out in
# the example .env. Appends the line if the key is not present at all.
set_feature_flag() {
    local key="$1" value="$2" file="$3"
    # Match only a bare assignment line (optionally commented): "KEY=" or
    # "KEY=value" with no trailing prose, so explanatory comments that mention
    # the key are left untouched.
    if grep -qE "^#? *${key}=[^[:space:]]*$" "$file"; then
        sed -i.bak -E "s|^#? *${key}=[^[:space:]]*$|${key}=${value}|" "$file"
        rm -f "${file}.bak"
    else
        printf '%s=%s\n' "$key" "$value" >> "$file"
    fi
}

# Generate a short, random shared key for the extension↔DNA binding.
# 12 hex chars (6 random bytes) — short enough to paste, random enough to gate.
generate_extension_key() {
    python3 -c "import secrets; print(secrets.token_hex(6))"
}

# Read the extension key currently configured for this instance: the value
# generated this run if any, otherwise whatever is in the backend compose file
# (so `--start` and re-runs still report the right key).
current_extension_key() {
    if [[ -n "$EXTENSION_KEY" ]]; then
        echo "$EXTENSION_KEY"
        return
    fi
    grep -E '^[[:space:]]*-?[[:space:]]*DNA_EXTENSION_KEY=' \
        "$BACKEND_DIR/docker-compose.local.yml" 2>/dev/null \
        | tail -n1 \
        | sed -E 's|.*DNA_EXTENSION_KEY=||' \
        | tr -d ' "'
}

# Map a user answer (o/on, f/off, u/blank) to "true", "false", or "" (unset).
normalize_flag() {
    case "$1" in
        o|[oO][nN])   echo "true" ;;
        f|[oO][fF][fF]) echo "false" ;;
        *)            echo "" ;;
    esac
}

# True once bootstrap has written the env files a later run should edit in place.
env_is_initialized() {
    [[ -f "$BACKEND_DIR/docker-compose.local.yml" && -f "$FRONTEND_ENV" ]]
}

# Read KEY from a compose `- KEY=value` line. Empty when the key is absent.
read_compose_value() {
    local key="$1" file="$2" line
    line="$(grep -E "^[[:space:]]*-[[:space:]]*${key}=" "$file" 2>/dev/null | tail -n1 || true)"
    if [[ -z "$line" ]]; then
        echo ""
        return 0
    fi
    echo "$line" | sed -E "s/.*${key}=//" | tr -d ' "'
}

# Read an active (uncommented) KEY=value from a dotenv file.
read_active_dotenv() {
    local key="$1" file="$2" line
    line="$(grep -E "^${key}=" "$file" 2>/dev/null | tail -n1 || true)"
    if [[ -z "$line" ]]; then
        echo ""
        return 0
    fi
    echo "${line#*=}"
}

