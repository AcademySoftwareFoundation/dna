    fi
}

current_prodtrack_label() {
    local provider
    provider="$(read_compose_value PRODTRACK_PROVIDER "$BACKEND_DIR/docker-compose.local.yml")"
    echo "${provider:-mock}"
}

current_feature_flags_label() {
    local in_review trans ai
    in_review="$(read_active_dotenv VITE_FEATURE_IN_REVIEW "$FRONTEND_ENV")"
    trans="$(read_active_dotenv VITE_FEATURE_TRANSCRIPTION "$FRONTEND_ENV")"
    ai="$(read_active_dotenv VITE_FEATURE_AI "$FRONTEND_ENV")"
    if [[ -z "$in_review" && -z "$trans" && -z "$ai" ]]; then
        echo "user-controlled"
        return 0
    fi
    echo "in-review=${in_review:-user}, transcription=${trans:-user}, ai=${ai:-user}"
}

# Comment a frontend flag back out so each user controls it again.
clear_feature_flag() {
    local key="$1" file="$2"
    if grep -qE "^#? *${key}=" "$file"; then
        sed -i.bak -E "s|^#? *${key}=.*|# ${key}=|" "$file"
        rm -f "${file}.bak"
    fi
}

# Replace every LLM provider entry in the compose file with the given KEY=VALUE
# pairs. Old provider keys are removed so switching providers does not leave
# the previous provider selected.
write_llm_block() {
    local needs_extra_hosts="$1"
    shift
    local file="$BACKEND_DIR/docker-compose.local.yml"
    local payload="" spec key value
    for spec in "$@"; do
        key="${spec%%=*}"
        value="${spec#*=}"
        payload+="${key}=$(escape_compose_value "$value")"$'\n'
    done
    python3 - "$file" "$needs_extra_hosts" "$payload" <<'PY'
import sys

path, needs_extra_hosts, payload = sys.argv[1], sys.argv[2] == "true", sys.argv[3]
LLM_KEYS = {
    "LLM_PROVIDER",
    "OPENAI_API_KEY",
    "ANTHROPIC_API_KEY",
    "ANTHROPIC_MODEL",
    "GEMINI_API_KEY",
    "CUSTOM_LLM_URL",
    "CUSTOM_LLM_MODEL",
    "CUSTOM_LLM_API_KEY",
}
new_entries = [line for line in payload.splitlines() if "=" in line]

with open(path) as f:
    lines = f.readlines()

def llm_key(line):
    stripped = line.lstrip()
    if not stripped.startswith("- "):
        return None
    body = stripped[2:].strip()
    key = body.split("=", 1)[0].strip()
    return key if key in LLM_KEYS else None

kept = []
insert_at = None
indent = "      "
for line in lines:
    if llm_key(line):
        if insert_at is None:
            insert_at = len(kept)
            indent = line[: len(line) - len(line.lstrip())]
        continue
    kept.append(line)

if insert_at is None:
    insert_at = len(kept)
    for i, line in enumerate(kept):
        stripped = line.lstrip()
        if stripped.startswith("- ") and "=" in stripped:
            insert_at = i + 1
            indent = line[: len(line) - len(stripped)]

block = [f"{indent}- {entry}\n" for entry in new_entries]
out = kept[:insert_at] + block + kept[insert_at:]

if needs_extra_hosts and not any(line.lstrip().startswith("extra_hosts:") for line in out):
    env_idx = next(
        (i for i, line in enumerate(out) if line.lstrip().startswith("environment:")),
        None,
    )
    if env_idx is not None:
        env_indent = len(out[env_idx]) - len(out[env_idx].lstrip())
        at = env_idx + 1
        while at < len(out):
            raw = out[at]
            if raw.strip() == "" or raw.lstrip().startswith("#"):
                at += 1
                continue
            if len(raw) - len(raw.lstrip()) > env_indent:
                at += 1
                continue
            break
        pad = " " * env_indent
        out.insert(at, f"{pad}extra_hosts:\n")
        out.insert(at + 1, f'{pad}  - "host.docker.internal:host-gateway"\n')

with open(path, "w") as f:
    f.writelines(out)
PY
}

# Apply one feature flag: write it to the frontend .env, or report it as left
# user-controlled when the value is empty. $4 is an optional note (e.g. cascade).
apply_feature_flag() {
    local key="$1" label="$2" value="$3" note="${4:-}"
    if [[ -z "$value" ]]; then
        ok "${label} left user-controlled"
        return
    fi
    set_feature_flag "$key" "$value" "$FRONTEND_ENV"
    local state="ON"; [[ "$value" == "false" ]] && state="OFF"
    if [[ -n "$note" ]]; then
        ok "${label} forced ${state} (${note}) in frontend/packages/app/.env"
    else
        ok "${label} forced ${state} in frontend/packages/app/.env"
    fi
}

# ── step 1: prerequisites ──────────────────────────────────────────────────────

check_prerequisites() {
    info "Checking prerequisites..."

    command -v node &>/dev/null \
        || die "Node.js not found. Install Node.js v18+: https://nodejs.org/en/download"
    local node_major
    node_major="$(node --version | sed 's/v//' | cut -d. -f1)"
    [[ "$node_major" -ge 18 ]] \
        || die "Node.js v18+ required (found $(node --version)). Upgrade: https://nodejs.org/en/download"
    ok "Node.js $(node --version)"

    command -v npm &>/dev/null \
        || die "npm not found. Install Node.js v18+: https://nodejs.org/en/download"
    ok "npm $(npm --version)"

    command -v python3 &>/dev/null \
        || die "python3 not found. Install Python 3: https://www.python.org/downloads/"
    ok "python3 $(python3 --version | awk '{print $2}')"

    command -v docker &>/dev/null \
        || die "Docker not found. Install Docker: https://docs.docker.com/get-docker/"
    ok "Docker $(docker --version | awk '{gsub(/,/,"",$3); print $3}')"

    docker info &>/dev/null \
        || die "Docker daemon is not running. Start Docker Desktop (or the service) and try again."
    ok "Docker daemon is running"
}

# ── step 2: copy example config files ─────────────────────────────────────────

copy_config_files() {
    info "Copying example config files..."
    safe_copy \
        "$BACKEND_DIR/example.docker-compose.local.yml" \
        "$BACKEND_DIR/docker-compose.local.yml"
    if [[ "$TRANSCRIPTION_ROUTE" != "extension" ]]; then
        safe_copy \
            "$BACKEND_DIR/example.docker-compose.local.vexa.yml" \
            "$BACKEND_DIR/docker-compose.local.vexa.yml"
    else
        info "Skipping Vexa compose overrides (browser-extension transcription route)"
    fi
    safe_copy \
        "$FRONTEND_DIR/packages/app/.env.example" \
        "$FRONTEND_DIR/packages/app/.env"
}

# ── step 3: LLM provider setup ─────────────────────────────────────────────────

configure_llm() {
    echo ""
    echo -e "${BOLD}LLM provider setup${NC}"
    echo "  (Press Enter on any prompt to skip and fill in manually later)"
    echo ""
    echo "  1) OpenAI  (default)"
    echo "  2) Anthropic (Claude)"
    echo "  3) Gemini"
    echo "  4) Custom  (OpenAI-compatible)"
    echo "  5) Skip"
    echo ""
    read -r -p "  Choice [1]: " llm_choice
    llm_choice="${llm_choice:-1}"
    echo ""

    case "$llm_choice" in
        2|[aA]nthropic|[cC]laude)
            read -r -p "  Anthropic API key: " anthropic_key
            if [[ -n "$anthropic_key" ]]; then
                write_llm_block false \
                    "LLM_PROVIDER=anthropic" \
                    "ANTHROPIC_API_KEY=${anthropic_key}" \
                    "ANTHROPIC_MODEL=claude-opus-4-8"
                ok "Anthropic API key written to backend/docker-compose.local.yml"
            else
                warn "Skipped — set ANTHROPIC_API_KEY and LLM_PROVIDER=anthropic in backend/docker-compose.local.yml"
            fi
            ;;
        3|[gG]emini)
            read -r -p "  Gemini API key: " gemini_key
            if [[ -n "$gemini_key" ]]; then
                write_llm_block false \
                    "LLM_PROVIDER=gemini" \
                    "GEMINI_API_KEY=${gemini_key}"
                ok "Gemini API key written to backend/docker-compose.local.yml"
            else
                warn "Skipped — set GEMINI_API_KEY and LLM_PROVIDER=gemini in backend/docker-compose.local.yml"
            fi
            ;;
        4|[cC]ustom)
            local default_url="http://host.docker.internal:11434/v1"
            local default_model="llama3.2:latest"

            read -r -p "  Custom LLM URL [${default_url}]: " custom_url
            custom_url="${custom_url:-$default_url}"

            # Warn if the URL uses localhost as hostname
            if [[ "$custom_url" =~ localhost ]]; then
                warn "URL uses 'localhost' — this will not work from a Docker container."
                warn "Use 'host.docker.internal' to refer to the Docker host from within a container."
                warn "  Example: ${default_url}"
            fi

            read -r -p "  Custom LLM model [${default_model}]: " custom_model
            custom_model="${custom_model:-$default_model}"

            read -r -p "  Custom LLM API key required? (y/N): " api_key_required
            api_key_required="${api_key_required:-n}"

            local custom_api_key=""
            if [[ "$api_key_required" =~ ^[yY]([eE][sS])?$ ]]; then
                read -r -p "  Custom LLM API key: " custom_api_key
            fi

            local needs_extra_hosts=false
            if [[ "$(uname -s)" == "Linux" ]] && [[ "$custom_url" =~ host\.docker\.internal ]]; then
                needs_extra_hosts=true
            fi

            local -a llm_entries=(
                "LLM_PROVIDER=custom"
                "CUSTOM_LLM_URL=${custom_url}"
                "CUSTOM_LLM_MODEL=${custom_model}"
            )
            if [[ -n "$custom_api_key" ]]; then
                llm_entries+=("CUSTOM_LLM_API_KEY=${custom_api_key}")
            fi
            write_llm_block "$needs_extra_hosts" "${llm_entries[@]}"

            if [[ -n "$custom_api_key" ]]; then
                ok "Custom LLM configured in backend/docker-compose.local.yml (URL, model, and API key)"
            else
                ok "Custom LLM configured in backend/docker-compose.local.yml (URL and model)"
            fi

            if [[ "$needs_extra_hosts" == "true" ]]; then
                ok "extra_hosts entry added for host.docker.internal (Linux detected)"
            fi
            ;;
        5|[sS]kip)
            warn "Skipped — set your LLM API key in backend/docker-compose.local.yml"
            ;;
        *)
            read -r -p "  OpenAI API key: " openai_key
            if [[ -n "$openai_key" ]]; then
                write_llm_block false "OPENAI_API_KEY=${openai_key}"
                ok "OpenAI API key written to backend/docker-compose.local.yml"
            else
                warn "Skipped — set OPENAI_API_KEY in backend/docker-compose.local.yml"
            fi
            ;;
    esac
}

# ── step 3.5: transcription route ─────────────────────────────────────────────

choose_transcription_route() {
    echo ""
    echo -e "${BOLD}Transcription route${NC}"
    echo "  Choose how meeting audio is transcribed."
    echo ""
    echo -e "  1) Vexa bot  ${BOLD}(default — server-side bot joins Meet/Teams)${NC}"
    echo ""
    echo "  2) Browser extension  (Chrome extension + WhisperLive — no Vexa)"
    echo "     Load prodtrack-tab-sync-extension/ unpacked in Chrome"
    echo ""
    read -r -p "  Choice [1]: " route_choice
    route_choice="${route_choice:-1}"
    echo ""

    case "$route_choice" in
        2|[eE]xtension*)
            TRANSCRIPTION_ROUTE="extension"
            ;;
        *)
            TRANSCRIPTION_ROUTE="vexa"
            ;;
    esac
}

# ── step 3.6: Vexa deployment (self-hosted vs hosted cloud) ───────────────────

configure_vexa() {
    echo ""
    echo -e "${BOLD}Vexa setup${NC}"
    echo "  Vexa provides the meeting bot and transcription that DNA consumes."
    echo ""
    echo -e "  1) Self-hosted Vexa  ${BOLD}(default — runs locally in Docker)${NC}"
    echo "  2) Hosted Vexa  (api.cloud.vexa.ai)"
    echo ""
    read -r -p "  Choice [1]: " vexa_choice
    vexa_choice="${vexa_choice:-1}"
    echo ""

    case "$vexa_choice" in
        2|[hH]osted|[cC]loud)
            VEXA_HOSTED=true
            set_env_var "VEXA_API_URL" "$VEXA_CLOUD_URL" \
                "$BACKEND_DIR/docker-compose.local.yml"
            ok "Vexa API URL set to ${VEXA_CLOUD_URL}"
            read -r -p "  Vexa cloud API key (from https://www.vexa.ai, or Enter to skip): " vexa_cloud_key
            if [[ -n "$vexa_cloud_key" ]]; then
                set_env_var "VEXA_API_KEY" "$vexa_cloud_key" \
                    "$BACKEND_DIR/docker-compose.local.yml"
                ok "Vexa cloud API key written to backend/docker-compose.local.yml"
            else
                warn "Skipped — set VEXA_API_KEY in backend/docker-compose.local.yml"
            fi
            info "Local Vexa container and transcription-backend setup will be skipped."
            ;;
        *)
            VEXA_HOSTED=false
            ensure_env_var "VEXA_API_URL" "$VEXA_LOCAL_URL" \
                "$BACKEND_DIR/docker-compose.local.yml"
            ok "Vexa API URL set to ${VEXA_LOCAL_URL}"
            ;;
    esac
}

detect_transcription_route() {
    if grep -qE 'DNA_ENABLE_EXTENSION_TRANSCRIPTION=(true|"true")' \
            "$BACKEND_DIR/docker-compose.local.yml" 2>/dev/null; then
        echo "extension"
    else
        echo "vexa"
    fi
}

configure_extension_transcription() {
    echo "  Browser-extension transcription setup:"
    echo "    1. Chrome → Extensions → Developer mode → Load unpacked"
    echo "       Select: prodtrack-tab-sync-extension/"
    echo "    2. Copy the extension ID (32 characters) from chrome://extensions"
    echo ""
    read -r -p "  Extension ID (press Enter to skip and set later): " ext_id
    local default_wl="ws://localhost:9090"
    read -r -p "  WhisperLive WebSocket URL [${default_wl}]: " wl_url
    wl_url="${wl_url:-$default_wl}"

    ensure_env_var "DNA_ENABLE_EXTENSION_TRANSCRIPTION" "true" \
        "$BACKEND_DIR/docker-compose.local.yml"
    ensure_env_var "TRANSCRIPTION_PROVIDER" "browser_extension" \
        "$BACKEND_DIR/docker-compose.local.yml"
    ok "Extension transcription enabled in backend/docker-compose.local.yml"

    # Generate the shared key once and place it in every location that needs it:
    # the backend (validates it on the ingest socket) and the frontend (sends it
    # on activation). The extension gets it via the popup — see print_summary.
    EXTENSION_KEY="$(generate_extension_key)"
    ensure_env_var "DNA_EXTENSION_KEY" "$EXTENSION_KEY" \
        "$BACKEND_DIR/docker-compose.local.yml"
    set_feature_flag "VITE_TRANSCRIPTION_EXTENSION_KEY" "$EXTENSION_KEY" "$FRONTEND_ENV"
    ok "Generated shared extension key → backend/docker-compose.local.yml + frontend/packages/app/.env"
    echo -e "  DNA extension key (paste into the extension popup): ${BOLD}${EXTENSION_KEY}${NC}"

    set_feature_flag "VITE_WHISPERLIVE_URL" "$wl_url" "$FRONTEND_ENV"
    ok "VITE_WHISPERLIVE_URL=${wl_url} in frontend/packages/app/.env"

    if [[ -n "$ext_id" ]]; then
        set_feature_flag "VITE_TRANSCRIPTION_EXTENSION_ID" "$ext_id" "$FRONTEND_ENV"
        set_feature_flag "VITE_PRODTRACK_TAB_SYNC_EXTENSION_ID" "$ext_id" "$FRONTEND_ENV"
        ok "Extension ID written to frontend/packages/app/.env"
    else
        warn "Skipped — set VITE_TRANSCRIPTION_EXTENSION_ID in frontend/packages/app/.env"
    fi
}

# ── step 4: transcription service setup ───────────────────────────────────────

# Append SKIP_TRANSCRIPTION_CHECK=true to docker-compose.local.vexa.yml so
# Vexa starts even without a working transcription backend.
add_skip_transcription_check() {
    python3 - "$BACKEND_DIR/docker-compose.local.vexa.yml" <<'PYEOF'
import sys

path = sys.argv[1]
with open(path) as f:
    lines = f.readlines()

if any('SKIP_TRANSCRIPTION_CHECK' in l for l in lines):
    sys.exit(0)

last_env_idx = -1
for i, line in enumerate(lines):
    stripped = line.lstrip()
    if stripped.startswith('- ') and '=' in stripped:
        last_env_idx = i

if last_env_idx >= 0:
    indent = lines[last_env_idx][: len(lines[last_env_idx]) - len(lines[last_env_idx].lstrip())]
    lines.insert(last_env_idx + 1, f"{indent}- SKIP_TRANSCRIPTION_CHECK=true\n")
    with open(path, 'w') as f:
        f.writelines(lines)
PYEOF
    ok "SKIP_TRANSCRIPTION_CHECK=true added to backend/docker-compose.local.vexa.yml"
}

